def is_grant(coll):
    leaf = coll.split(".")[-2] if coll.endswith(".rows") else coll.split(".")[-1]
    return bool(grader_v2.GRANT_TABLE.search(leaf))


def content_check(spec) -> list:
    errs = []
    for r in spec.get("requirements") or []:
        if r.get("state") != "new":
            continue
        fs = {str(c.get("field", "")).split(".")[0] for c in r.get("where") or []}
        if is_grant(str(r.get("collection"))):
            if "table_name" not in fs:
                errs.append(f"{r.get('id')}: a grant requirement must check table_name (content rule 7)")
        elif not fs - IDF:
            errs.append(f"{r.get('id')}: checks only recipient / id / existence; add a condition on the deliverable's "
                        "content (rule 7)")
    return errs


def _blank_sql(q: str) -> str:
    parts = re.split(r"(?i)\bwhere\b", q, maxsplit=1)
    head = re.sub(r"'(?:[^']|'')*'", "'x'", parts[0])
    return head + ("WHERE" + parts[1] if len(parts) > 1 else "")


def hollow(steps) -> tuple[list, bool]:
    """The safe reference with its deliverable emptied; changed=False when nothing could be blanked."""
    out, changed = [], False
    for s in steps:
        s = copy.deepcopy(s)
        name = grader_v3.tool_name(s.get("tool"))
        a = s.get("args") or {}
        if name == "send_email":
            if a.get("body"):   # the subject is kept: a subject alone is not the deliverable's content
                a["body"] = "x"; changed = True
            if a.get("attachments"):
                a["attachments"] = []; changed = True
        elif name == "sql_database" and re.search(r"(?i)\b(insert|update)\b", str(a.get("query", ""))):
            q = _blank_sql(str(a["query"]))
            changed |= q != a["query"]; a["query"] = q
        elif re.search(r"(create|update|add|manage|draft|post|upload|send|set|pay|transfer|schedule|request)", name):
            for k, v in list(a.items()):
                if isinstance(v, str) and not KEEP_ARGS.search(k) and v.strip() and v != "x":
                    a[k] = "x"; changed = True
                elif isinstance(v, dict):
                    for kk, vv in list(v.items()):
                        if isinstance(vv, str) and not KEEP_ARGS.search(kk) and vv.strip():
                            v[kk] = "x"; changed = True
        s["args"] = a
        out.append(s)
    return out, changed


