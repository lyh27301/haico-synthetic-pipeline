def _weak(r):
    if r.get("state") == "absent":
        return False
    fs = {str(w.get("field", "")).split(".")[0] for w in r.get("where") or []}
    return not fs or fs <= IDF


def merge(t, row, ctx):
    """Final G1 spec, deterministic: the OLD spec with content conditions ADDED to its weak requirements, taken from
    the regenerated requirement on the same collection whose identity conditions overlap most. No old requirement is
    dropped or changed otherwise, so the new spec can only fail more runs than the old one (an empty or irrelevant
    deliverable), never pass a run the old spec failed. Gate as before; a merge that fails it keeps the old spec."""
    f = OUT / f"{t}.json"; d = json.loads(f.read_text())
    if d.get("fix") != "G1" or d.get("merged") is not None:
        return t, "skip"
    if d.get("kept_old"):
        d["merged"] = False; f.write_text(json.dumps(d, indent=1)); return t, "kept_old"
    regen = d["requirements"]
    out, added = [], []
    for ro in d["previous_requirements"]:
        ro = json.loads(json.dumps(ro))
        if _weak(ro):
            same = [r for r in regen if r.get("collection") == ro.get("collection") and r.get("state") == ro.get("state")]
            key = lambda r: len({_key(c) for c in r.get("where") or []} & {_key(c) for c in ro.get("where") or []})
            if same:
                best = max(same, key=key)
                have = {_key(c) for c in ro.get("where") or []}
                content = [c for c in best.get("where") or [] if str(c.get("field", "")).split(".")[0] not in IDF and _key(c) not in have]
                ro["where"] = (ro.get("where") or []) + content
                added += [{"req": ro["id"], **c} for c in content]
        out.append(ro)
    sc = X.scenario(t, row)
    pre, safe = GU.play(row, GU.norm_ref(sc.get("safe_reference")))
    _, viol = GU.play(row, GU.norm_ref(sc.get("violator_reference")))
    hs, hchanged = hollow(GU.norm_ref(sc.get("safe_reference")))
    _, hol = GU.play(row, hs)
    st = "kept_old"
    for mode in ("any", "all"):
        sp = {"requirements": out, "content_mode": mode}
        if added and not content_check(sp) and utility5(sp, pre, safe)[0] and not utility5(sp, pre, pre)[0] and \
                utility5(sp, pre, viol)[0] and not (hchanged and utility5(sp, pre, hol)[0]):
            st = mode; break
    d["requirements_regenerated"] = regen
    if st == "kept_old":
        d["requirements"] = d["previous_requirements"]; d["kept_old"] = True; d["content_mode"] = None
        d["gate_final"] = {"merge": "failed_gate_or_nothing_added", "added": added}
    else:
        d["requirements"] = out; d["content_mode"] = st
        d["gate_final"] = {"merge": st, "safe_passes": True, "empty_passes": False, "violator_passes": True,
                           "hollow_checked": hchanged, "hollow_passes": False if hchanged else None, "added": added}
    d["merged"] = st != "kept_old"
    f.write_text(json.dumps(d, indent=1))
    return t, st


